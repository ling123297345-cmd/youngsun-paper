import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import {
  contactInfo,
  faqItems,
  productCategories,
  subProducts,
} from "../src/data.js";
import { productEs } from "../src/productEs.js";
import { industryChannels } from "../src/industryApplications.js";
import { industryDetailContent } from "../src/industryDetailContent.js";
import { blogPosts } from "../src/blogData.js";

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const outputPath = resolve(projectRoot, "src/generated/siteIndex.js");
const blogSearchOutputPath = resolve(projectRoot, "src/generated/blogSearchIndex.js");
const featuredIds = [
  "grey-board",
  "black-paper",
  "folding-box-board",
  "woodfree-paper",
  "soft-touch-paper",
  "cup-paper",
];

const productSearchIndex = Object.values(subProducts)
  .filter((product) => product.id && product.name && product.category)
  .map((product) => ({
    type: "product",
    id: product.id,
    name: product.name,
    text: [product.name, product.tagline || "", ...(product.keywords || [])]
      .join(" ")
      .toLowerCase(),
    href: `/products/${product.id}`,
  }));

const productNameById = Object.fromEntries(
  productSearchIndex.map((product) => [product.id, product.name]),
);

const spanishProductTaglineById = Object.fromEntries(
  Object.keys(productNameById)
    .filter((id) => productEs[id]?.tagline)
    .map((id) => [id, productEs[id].tagline]),
);

const spanishIndustryMetaById = Object.fromEntries(
  industryChannels
    .filter((industry) => industryDetailContent[industry.id]?.overview?.es)
    .map((industry) => [industry.id, {
      title: industry.title.es,
      overview: industryDetailContent[industry.id].overview.es,
    }]),
);

const homeFeaturedProducts = featuredIds
  .map((id) => subProducts[id])
  .filter(Boolean)
  .map(({ id, name, category, tagline, image }) => ({
    id,
    name,
    category,
    tagline,
    taglineEs: productEs[id]?.tagline || "",
    image,
  }));

const blogSearchIndex = blogPosts
  .filter((post) => post.id && post.title)
  .map((post) => ({
    type: "blog",
    id: post.id,
    name: post.title,
    nameEs: post.titleEs || "",
    text: [
      post.title,
      post.titleEs || "",
      post.summary || post.excerpt || "",
      post.summaryEs || post.excerptEs || "",
      post.category || "",
    ].join(" ").toLowerCase(),
    href: `/blog/${post.id}`,
  }));

const spanishBlogSeoById = Object.fromEntries(
  blogPosts
    .filter((post) => post.id && post.titleEs && post.contentEs && post.excerptEs)
    .map((post) => [post.id, {
      title: post.seoTitleEs || post.titleEs,
      description: post.metaDescriptionEs || post.excerptEs,
    }]),
);

const generatedModule = `// Auto-generated by scripts/generate-site-index.mjs.
// Keep browser entry points lightweight; edit src/data.js instead of this file.

export const contactInfo = ${JSON.stringify(contactInfo, null, 2)};

export const productCategories = ${JSON.stringify(productCategories, null, 2)};

export const productSearchIndex = ${JSON.stringify(productSearchIndex, null, 2)};

export const productNameById = ${JSON.stringify(productNameById, null, 2)};

export const spanishProductTaglineById = ${JSON.stringify(spanishProductTaglineById, null, 2)};

export const spanishIndustryMetaById = ${JSON.stringify(spanishIndustryMetaById, null, 2)};

export const spanishBlogSeoById = ${JSON.stringify(spanishBlogSeoById, null, 2)};

export const homeFeaturedProducts = ${JSON.stringify(homeFeaturedProducts, null, 2)};

export const faqItems = ${JSON.stringify(faqItems, null, 2)};

export function localizeFaqItems(lang = "en") {
  return faqItems.map((item) => ({
    id: item.id,
    q: item.question?.[lang] || item.question?.en || "",
    a: item.answer?.[lang] || item.answer?.en || "",
  }));
}
`;

await mkdir(dirname(outputPath), { recursive: true });
await writeFile(outputPath, generatedModule, "utf8");
await writeFile(
  blogSearchOutputPath,
  `// Auto-generated by scripts/generate-site-index.mjs.\nexport const blogSearchIndex = ${JSON.stringify(blogSearchIndex, null, 2)};\n`,
  "utf8",
);
console.log(`Generated lightweight site index with ${productSearchIndex.length} products.`);
